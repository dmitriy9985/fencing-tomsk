-- Структурированные результаты соревнований.
--
-- Выполняйте файл целиком в Supabase Dashboard -> SQL Editor до запуска
-- seed-existing-structured-results.sql. Миграция идемпотентна и сохраняет
-- существующие строки public.competition_results.

begin;

-- competition_results остаётся записью о турнире. Новые поля необязательны,
-- поэтому старые опубликованные результаты продолжают работать без изменений.
alter table public.competition_results
  add column if not exists event_id bigint,
  add column if not exists news_id bigint,
  add column if not exists city text not null default '',
  add column if not exists protocol_url text;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'competition_results_event_id_fkey'
      and conrelid = 'public.competition_results'::regclass
  ) then
    alter table public.competition_results
      add constraint competition_results_event_id_fkey
      foreign key (event_id) references public.competition_events(id)
      on delete set null;
  end if;

  if not exists (
    select 1 from pg_constraint
    where conname = 'competition_results_news_id_fkey'
      and conrelid = 'public.competition_results'::regclass
  ) then
    alter table public.competition_results
      add constraint competition_results_news_id_fkey
      foreign key (news_id) references public.news(id)
      on delete set null;
  end if;

  if not exists (
    select 1 from pg_constraint
    where conname = 'competition_results_city_length_check'
      and conrelid = 'public.competition_results'::regclass
  ) then
    alter table public.competition_results
      add constraint competition_results_city_length_check
      check (char_length(city) <= 200);
  end if;

  if not exists (
    select 1 from pg_constraint
    where conname = 'competition_results_protocol_url_check'
      and conrelid = 'public.competition_results'::regclass
  ) then
    alter table public.competition_results
      add constraint competition_results_protocol_url_check
      check (
        protocol_url is null
        or (
          char_length(btrim(protocol_url)) between 1 and 2048
          and protocol_url ~ '^https?://'
        )
      );
  end if;
end
$$;

-- Турнир может быть опубликован и без призовых мест: например, если доступен
-- только официальный протокол. Старое поле остаётся безопасным fallback.
alter table public.competition_results
  drop constraint if exists competition_results_result_text_check;

alter table public.competition_results
  alter column result_text set default '';

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'competition_results_result_text_length_check'
      and conrelid = 'public.competition_results'::regclass
  ) then
    alter table public.competition_results
      add constraint competition_results_result_text_length_check
      check (char_length(result_text) <= 5000);
  end if;
end
$$;

create index if not exists competition_results_event_id_idx
  on public.competition_results (event_id)
  where event_id is not null;

create index if not exists competition_results_news_id_idx
  on public.competition_results (news_id)
  where news_id is not null;

create table if not exists public.competition_result_entries (
  id bigint generated by default as identity primary key,
  competition_result_id bigint not null
    references public.competition_results(id) on delete cascade,
  place smallint not null
    check (place between 1 and 999),
  participant_name text not null
    check (char_length(btrim(participant_name)) between 1 and 300),
  weapon text not null default ''
    check (char_length(weapon) <= 100),
  age_category text not null default ''
    check (char_length(age_category) <= 150),
  competition_format text not null default 'individual'
    check (competition_format in ('individual', 'team')),
  team_members text[] not null default '{}'::text[],
  sort_order integer not null default 0
    check (sort_order >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists competition_result_entries_parent_order_idx
  on public.competition_result_entries
  (competition_result_id, sort_order, place, created_at);

drop trigger if exists set_competition_result_entries_updated_at
  on public.competition_result_entries;
create trigger set_competition_result_entries_updated_at
before update on public.competition_result_entries
for each row execute function public.set_site_admin_updated_at();

alter table public.competition_result_entries enable row level security;

revoke all on public.competition_result_entries from anon, authenticated;
grant select on public.competition_result_entries to anon, authenticated;
grant insert, update, delete on public.competition_result_entries to authenticated;
grant usage, select on sequence public.competition_result_entries_id_seq
  to authenticated;

drop policy if exists "Visitors can read entries from published results"
  on public.competition_result_entries;
create policy "Visitors can read entries from published results"
on public.competition_result_entries
for select
to anon, authenticated
using (
  exists (
    select 1
    from public.competition_results
    where competition_results.id = competition_result_entries.competition_result_id
      and competition_results.published = true
  )
);

drop policy if exists "Admins can manage competition result entries"
  on public.competition_result_entries;
create policy "Admins can manage competition result entries"
on public.competition_result_entries
for all
to authenticated
using (
  exists (
    select 1 from public.admin_users
    where admin_users.user_id = (select auth.uid())
  )
)
with check (
  exists (
    select 1 from public.admin_users
    where admin_users.user_id = (select auth.uid())
  )
);

commit;
