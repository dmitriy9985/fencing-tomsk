  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

-- Публичность bucket означает, что известный URL файла доступен напрямую.
-- published=false скрывает альбом из публичных запросов к таблицам, но не
-- является механизмом секретности уже загруженных файлов.
drop policy if exists "Visitors can read site admin images"
  on storage.objects;
create policy "Visitors can read site admin images"
on storage.objects
for select
to anon, authenticated
using (bucket_id in ('gallery-images', 'site-images'));

drop policy if exists "Admins can manage gallery images"
  on storage.objects;
create policy "Admins can manage gallery images"
on storage.objects
for all
to authenticated
using (
  bucket_id = 'gallery-images'
