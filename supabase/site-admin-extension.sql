create table if not exists public.competition_events (
  id bigint generated by default as identity primary key,
  title text not null
    check (char_length(btrim(title)) between 1 and 200),
  start_date date not null,
  end_date date,
  location text not null default ''
    check (char_length(location) <= 200),
  description text not null default ''
    check (char_length(description) <= 2000),
  category_label text not null default ''
    check (char_length(category_label) <= 100),
  short_label text not null default ''
    check (char_length(short_label) <= 12),
  published boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint competition_events_date_range_check
    check (end_date is null or end_date >= start_date)
);

create table if not exists public.competition_results (
  id bigint generated by default as identity primary key,
  competition_date date not null,
  date_label text
    check (date_label is null or char_length(date_label) <= 80),
  title text not null
    check (char_length(btrim(title)) between 1 and 200),
  result_text text not null
    check (char_length(btrim(result_text)) between 1 and 5000),
  category text not null default ''
    check (char_length(category) <= 200),
  published boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.gallery_albums (
  id bigint generated by default as identity primary key,
  title text not null
    check (char_length(btrim(title)) between 1 and 200),
  description text not null default ''
    check (char_length(description) <= 2000),
  event_date date,
  published boolean not null default false,
  sort_order integer not null default 0
    check (sort_order >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.gallery_photos (
  id bigint generated by default as identity primary key,
  album_id bigint not null
    references public.gallery_albums(id) on delete cascade,
  image_url text not null
    check (char_length(btrim(image_url)) between 1 and 2048),
  image_path text
    check (
      image_path is null
      or char_length(btrim(image_path)) between 1 and 1024
    ),
  caption text not null default ''
    check (char_length(caption) <= 500),
  alt_text text not null default ''
    check (char_length(alt_text) <= 300),
  sort_order integer not null default 0
    check (sort_order >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Только явно разрешённые текстовые поля и ссылки на изображения.
-- Произвольные HTML, CSS, JSON или шаблоны в этой таблице не хранятся.
create table if not exists public.home_content (
  id smallint primary key default 1,
  hero_kicker text not null default ''
    check (char_length(hero_kicker) <= 120),
  hero_title text not null default ''
    check (char_length(hero_title) <= 200),
  hero_subtitle text not null default ''
    check (char_length(hero_subtitle) <= 700),
  hero_image_url text not null default ''
    check (char_length(hero_image_url) <= 2048),
  hero_image_path text
    check (
      hero_image_path is null
      or char_length(btrim(hero_image_path)) between 1 and 1024
    ),
  hero_image_alt text not null default ''
    check (char_length(hero_image_alt) <= 300),
  about_eyebrow text not null default ''
    check (char_length(about_eyebrow) <= 120),
  about_title text not null default ''
    check (char_length(about_title) <= 200),
  about_text text not null default ''
    check (char_length(about_text) <= 5000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint home_content_singleton_check check (id = 1)
);

insert into public.home_content (id)
values (1)
on conflict (id) do nothing;

