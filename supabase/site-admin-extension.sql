create or replace function public.set_site_admin_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists set_competition_events_updated_at
  on public.competition_events;
create trigger set_competition_events_updated_at
before update on public.competition_events
